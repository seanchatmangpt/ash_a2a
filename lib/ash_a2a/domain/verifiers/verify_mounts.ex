defmodule AshA2A.Domain.Verifiers.VerifyMounts do
  @moduledoc """
  Verifies `AshA2A.Domain`'s `transport.mount` declarations:

  - every per-agent mount's `agent` module must exist (`Code.ensure_compiled/1`
    -- a misdeclared agent is a compile-time `Spark.Error.DslError` refusal).
  - mount paths must be unique across all declared mounts.
  - an agent may not be mounted twice over the same binding.
  """

  use Spark.Dsl.Verifier

  alias AshA2A.Domain.Mount

  @impl true
  def verify(dsl_state) do
    module = Spark.Dsl.Verifier.get_persisted(dsl_state, :module)

    mounts =
      dsl_state
      |> Spark.Dsl.Verifier.get_entities([:transport])
      |> Enum.filter(&match?(%Mount{}, &1))

    with :ok <- verify_agents_exist(mounts, module),
         :ok <- verify_agent_modules(mounts, module),
         :ok <- verify_path_shape(mounts, module),
         :ok <- verify_unique_paths(mounts, module),
         :ok <- verify_no_prefix_overlap(mounts, module),
         :ok <- verify_unique_agent_bindings(mounts, module) do
      warn_grpc(mounts)
    end
  end

  defp verify_agents_exist(mounts, module) do
    Enum.reduce_while(mounts, :ok, fn
      %Mount{agent: nil}, :ok ->
        {:cont, :ok}

      %Mount{agent: agent, path: path}, :ok ->
        case Code.ensure_compiled(agent) do
          {:module, _} ->
            {:cont, :ok}

          {:error, _} ->
            {:halt,
             {:error,
              Spark.Error.DslError.exception(
                module: module,
                path: [:transport, :mount],
                message:
                  "mount `#{path}` references agent `#{inspect(agent)}`, which does not exist " <>
                    "-- mounted agents must be compiled before the domain that mounts them"
              )}}
        end
    end)
  end

  # The mounted module must be a real `AshA2A.Agent` (an agent GenServer
  # generated by `use AshA2A.Agent`), not any compiled module.
  defp verify_agent_modules(mounts, module) do
    Enum.reduce_while(mounts, :ok, fn
      %Mount{agent: nil}, :ok ->
        {:cont, :ok}

      %Mount{agent: agent, path: path}, :ok ->
        if agent_module?(agent) do
          {:cont, :ok}
        else
          {:halt,
           {:error,
            Spark.Error.DslError.exception(
              module: module,
              path: [:transport, :mount],
              message:
                "mount `#{path}` references `#{inspect(agent)}`, which is not an AshA2A.Agent " <>
                  "(expected a module defined with `use AshA2A.Agent`)"
            )}}
        end
    end)
  end

  defp agent_module?(agent) do
    Code.ensure_loaded?(agent) and function_exported?(agent, :handle_cancel, 1) and
      function_exported?(agent, :init, 1) and function_exported?(agent, :agent_card, 0)
  end

  defp verify_path_shape(mounts, module) do
    case Enum.find(mounts, fn %Mount{path: path} -> not match?("/" <> _, path) end) do
      nil ->
        :ok

      %Mount{path: path} ->
        {:error,
         Spark.Error.DslError.exception(
           module: module,
           path: [:transport, :mount],
           message: "mount path #{inspect(path)} must start with \"/\""
         )}
    end
  end

  # `/a` and `/a/b` overlap: the router would match the shorter prefix first
  # and shadow the longer mount.
  defp verify_no_prefix_overlap(mounts, module) do
    segments = Enum.map(mounts, fn %Mount{path: path} -> {path, split(path)} end)

    overlap =
      for {p1, s1} <- segments,
          {p2, s2} <- segments,
          p1 != p2,
          s1 != [],
          List.starts_with?(s2, s1),
          do: {p1, p2}

    case overlap do
      [] ->
        :ok

      [{short, long} | _] ->
        {:error,
         Spark.Error.DslError.exception(
           module: module,
           path: [:transport, :mount],
           message:
             "mount path `#{short}` is a prefix of mount path `#{long}`; mounts must not overlap"
         )}
    end
  end

  defp split(path), do: String.split(path, "/", trim: true)

  defp warn_grpc(mounts) do
    case Enum.filter(mounts, &(&1.binding == :grpc)) do
      [] ->
        :ok

      grpc ->
        paths = Enum.map_join(grpc, ", ", &"`#{&1.path}`")

        {:warn,
         [
           "mount(s) #{paths} use the :grpc binding, which AshA2A.Domain.Router does not serve " <>
             "(it answers a typed 501); serve them with AshA2A.Transport.GRPC.Server.Endpoint"
         ]}
    end
  end

  defp verify_unique_paths(mounts, module) do
    mounts
    |> Enum.group_by(& &1.path)
    |> Enum.find(fn {_path, group} -> length(group) > 1 end)
    |> case do
      nil ->
        :ok

      {path, _group} ->
        {:error,
         Spark.Error.DslError.exception(
           module: module,
           path: [:transport, :mount],
           message: "mount path `#{path}` is declared more than once"
         )}
    end
  end

  defp verify_unique_agent_bindings(mounts, module) do
    mounts
    |> Enum.filter(&Mount.agent_mount?/1)
    |> Enum.group_by(fn %Mount{agent: agent, binding: binding} -> {agent, binding} end)
    |> Enum.find(fn {_key, group} -> length(group) > 1 end)
    |> case do
      nil ->
        :ok

      {{agent, binding}, _group} ->
        {:error,
         Spark.Error.DslError.exception(
           module: module,
           path: [:transport, :mount],
           message:
             "agent `#{inspect(agent)}` is mounted more than once over the `#{binding}` binding"
         )}
    end
  end
end
